-- Portiert von db/migration/V900__wartung_grundlagen.sql (MySQL) nach PostgreSQL.
-- Wartung: Objekte, Tueren/Tore, Vorlagenkatalog (Module) und Wartungsprotokolle.
--
-- Fachliche Hierarchie: Kunde -> Objekt -> Tuer/Tor -> Wartungsprotokoll.
-- Der Vorlagenkatalog (wartung_modul*) beschreibt, was geprueft wird (Brandschutztuer,
-- Feststellanlage, ...). Beim Anlegen eines Protokolls wird der Katalog als Kopie
-- (Snapshot) ins Protokoll uebernommen, spaetere Aenderungen am Katalog wirken nicht
-- rueckwirkend.
--
-- Eigener Versionsbereich ab V900, damit die Migrationen nicht mit kuenftigen
-- Upstream-Nummern kollidieren (Flyway laeuft hier mit out-of-order=true).
-- Alles idempotent. Enum-Spalten sind native ENUMs (siehe BACKEND_ARCH.md).

-- ── Objekte und Tueren/Tore ─────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS wartung_objekt (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    kunde_id BIGINT NOT NULL,
    bezeichnung VARCHAR(200) NOT NULL,
    strasse VARCHAR(200) NULL,
    plz VARCHAR(20) NULL,
    ort VARCHAR(120) NULL,
    ansprechpartner_name VARCHAR(200) NULL,
    ansprechpartner_telefon VARCHAR(60) NULL,
    notizen TEXT NULL,
    aktiv BOOLEAN NOT NULL DEFAULT TRUE,
    angelegt_am TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_wartung_objekt_kunde FOREIGN KEY (kunde_id) REFERENCES kunde(id)
);
CREATE INDEX IF NOT EXISTS idx_wartung_objekt_kunde ON wartung_objekt (kunde_id);

-- ── Vorlagenkatalog ─────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS wartung_modul (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    modul_key VARCHAR(60) NOT NULL,
    name VARCHAR(120) NOT NULL,
    beschreibung TEXT NULL,
    icon VARCHAR(40) NULL,
    kategorie VARCHAR(20) NOT NULL DEFAULT 'BASIS',
    system_modul BOOLEAN NOT NULL DEFAULT FALSE,
    aktiv BOOLEAN NOT NULL DEFAULT TRUE,
    sortierung INT NOT NULL DEFAULT 0,
    standard_intervall_monate INT NOT NULL DEFAULT 12,
    CONSTRAINT uk_wartung_modul_key UNIQUE (modul_key)
);

-- Zusatzmodule duerfen nur an bestimmte Basis-Elemente andocken. Keine Zeile = an jedes Basis-Element.
CREATE TABLE IF NOT EXISTS wartung_modul_andockbar (
    modul_id BIGINT NOT NULL,
    basis_modul_id BIGINT NOT NULL,
    PRIMARY KEY (modul_id, basis_modul_id),
    CONSTRAINT fk_wartung_andockbar_modul FOREIGN KEY (modul_id) REFERENCES wartung_modul(id) ON DELETE CASCADE,
    CONSTRAINT fk_wartung_andockbar_basis FOREIGN KEY (basis_modul_id) REFERENCES wartung_modul(id) ON DELETE CASCADE
);

-- Bauarten eines Moduls (z.B. 1-fluegelig, 2-fluegelig, Schiebetuer). Der Schluessel bleibt stabil,
-- auch wenn die Bezeichnung spaeter umbenannt wird.
CREATE TABLE IF NOT EXISTS wartung_modul_untertyp (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    modul_id BIGINT NOT NULL,
    schluessel VARCHAR(30) NOT NULL,
    label VARCHAR(100) NOT NULL,
    sortierung INT NOT NULL DEFAULT 0,
    CONSTRAINT uk_wartung_modul_untertyp UNIQUE (modul_id, schluessel),
    CONSTRAINT fk_wartung_untertyp_modul FOREIGN KEY (modul_id) REFERENCES wartung_modul(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS wartung_modul_abschnitt (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    modul_id BIGINT NOT NULL,
    bereich VARCHAR(20) NOT NULL,
    label VARCHAR(200) NOT NULL,
    sortierung INT NOT NULL DEFAULT 0,
    CONSTRAINT fk_wartung_modul_abschnitt_modul FOREIGN KEY (modul_id) REFERENCES wartung_modul(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_wartung_modul_abschnitt_modul ON wartung_modul_abschnitt (modul_id);

-- nur_bei_untertyp = NULL: gilt fuer alle Bauarten, sonst nur fuer die genannte.
CREATE TABLE IF NOT EXISTS wartung_modul_pruefpunkt (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    modul_id BIGINT NOT NULL,
    abschnitt_id BIGINT NULL,
    label VARCHAR(500) NOT NULL,
    nur_bei_untertyp VARCHAR(30) NULL,
    sortierung INT NOT NULL DEFAULT 0,
    CONSTRAINT fk_wartung_modul_pp_modul FOREIGN KEY (modul_id) REFERENCES wartung_modul(id) ON DELETE CASCADE,
    CONSTRAINT fk_wartung_modul_pp_abschnitt FOREIGN KEY (abschnitt_id) REFERENCES wartung_modul_abschnitt(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_wartung_modul_pp_modul ON wartung_modul_pruefpunkt (modul_id);

-- optionen: nur bei feldtyp AUSWAHL, eine Option pro Zeile.
CREATE TABLE IF NOT EXISTS wartung_modul_datenfeld (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    modul_id BIGINT NOT NULL,
    abschnitt_id BIGINT NULL,
    label VARCHAR(200) NOT NULL,
    feldtyp VARCHAR(20) NOT NULL DEFAULT 'TEXT',
    optionen TEXT NULL,
    sortierung INT NOT NULL DEFAULT 0,
    CONSTRAINT fk_wartung_modul_df_modul FOREIGN KEY (modul_id) REFERENCES wartung_modul(id) ON DELETE CASCADE,
    CONSTRAINT fk_wartung_modul_df_abschnitt FOREIGN KEY (abschnitt_id) REFERENCES wartung_modul_abschnitt(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_wartung_modul_df_modul ON wartung_modul_datenfeld (modul_id);

-- Datenfelder, die in jedes Protokoll kopiert werden, egal welche Module gewaehlt sind.
CREATE TABLE IF NOT EXISTS wartung_globales_datenfeld (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label VARCHAR(200) NOT NULL,
    feldtyp VARCHAR(20) NOT NULL DEFAULT 'TEXT',
    optionen TEXT NULL,
    sortierung INT NOT NULL DEFAULT 0
);

-- ── Tueren/Tore ─────────────────────────────────────────────────────────────

-- intervall_monate und naechste_faelligkeit bilden den Wartungsplan der Tuer. Die
-- naechste Faelligkeit wird beim Abschluss eines Protokolls fortgeschrieben.
CREATE TABLE IF NOT EXISTS wartung_tuer (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    objekt_id BIGINT NOT NULL,
    bezeichnung VARCHAR(200) NOT NULL,
    notizen TEXT NULL,
    intervall_monate INT NULL,
    naechste_faelligkeit DATE NULL,
    aktiv BOOLEAN NOT NULL DEFAULT TRUE,
    angelegt_am TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_wartung_tuer_objekt FOREIGN KEY (objekt_id) REFERENCES wartung_objekt(id)
);
CREATE INDEX IF NOT EXISTS idx_wartung_tuer_objekt ON wartung_tuer (objekt_id);
CREATE INDEX IF NOT EXISTS idx_wartung_tuer_faellig ON wartung_tuer (naechste_faelligkeit);

-- Welche Module (inkl. Bauart) zu dieser Tuer gehoeren. Dient als Vorbelegung fuer neue Protokolle.
CREATE TABLE IF NOT EXISTS wartung_tuer_modul (
    tuer_id BIGINT NOT NULL,
    modul_id BIGINT NOT NULL,
    untertyp_schluessel VARCHAR(30) NULL,
    PRIMARY KEY (tuer_id, modul_id),
    CONSTRAINT fk_wartung_tuer_modul_tuer FOREIGN KEY (tuer_id) REFERENCES wartung_tuer(id) ON DELETE CASCADE,
    CONSTRAINT fk_wartung_tuer_modul_modul FOREIGN KEY (modul_id) REFERENCES wartung_modul(id)
);

-- ── Nummernkreis ────────────────────────────────────────────────────────────

-- Genau eine Zeile je Praefix. Die Vergabe sperrt die Zeile (SELECT ... FOR UPDATE), damit zwei
-- gleichzeitige Anlagen nie dieselbe Nummer bekommen. Ein neues Jahr setzt den Zaehler unter
-- derselben Sperre zurueck. Die Zeile wird hier fest angelegt: Gaebe es nichts anzulegen, braeuchte
-- die Vergabe keine zweite Datenbankverbindung (das wuerde den Pool unter Last leerlaufen lassen).
CREATE TABLE IF NOT EXISTS wartung_nummernkreis (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    praefix VARCHAR(20) NOT NULL,
    jahr INT NOT NULL,
    letzter_wert INT NOT NULL DEFAULT 0,
    CONSTRAINT uk_wartung_nummernkreis UNIQUE (praefix)
);

INSERT INTO wartung_nummernkreis (praefix, jahr, letzter_wert)
SELECT 'WA', EXTRACT(YEAR FROM CURRENT_DATE)::int, 1000
WHERE NOT EXISTS (SELECT 1 FROM wartung_nummernkreis WHERE praefix = 'WA');

-- ── Wartungsprotokolle ──────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS wartung_protokoll (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    nummer VARCHAR(40) NOT NULL,
    kunde_id BIGINT NOT NULL,
    objekt_id BIGINT NULL,
    tuer_id BIGINT NULL,
    projekt_id BIGINT NULL,
    techniker_id BIGINT NULL,
    titel VARCHAR(200) NULL,
    protokoll_typ VARCHAR(100) NOT NULL DEFAULT 'Wartungsprotokoll',
    datum DATE NOT NULL,
    intervall_monate INT NOT NULL DEFAULT 12,
    naechste_wartung DATE NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'OFFEN',
    bemerkungen TEXT NULL,
    ansprechpartner_name VARCHAR(200) NULL,
    unterschrift_techniker TEXT NULL,
    unterschrift_techniker_name VARCHAR(200) NULL,
    unterschrift_kunde TEXT NULL,
    unterschrift_kunde_name VARCHAR(200) NULL,
    abgeschlossen_am TIMESTAMP(6) NULL,
    angelegt_am TIMESTAMP(6) NOT NULL,
    geaendert_am TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_wartung_protokoll_nummer UNIQUE (nummer),
    CONSTRAINT fk_wartung_protokoll_kunde FOREIGN KEY (kunde_id) REFERENCES kunde(id),
    CONSTRAINT fk_wartung_protokoll_objekt FOREIGN KEY (objekt_id) REFERENCES wartung_objekt(id),
    CONSTRAINT fk_wartung_protokoll_tuer FOREIGN KEY (tuer_id) REFERENCES wartung_tuer(id),
    CONSTRAINT fk_wartung_protokoll_projekt FOREIGN KEY (projekt_id) REFERENCES projekt(id) ON DELETE SET NULL,
    CONSTRAINT fk_wartung_protokoll_techniker FOREIGN KEY (techniker_id) REFERENCES mitarbeiter(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_wartung_protokoll_kunde ON wartung_protokoll (kunde_id);
CREATE INDEX IF NOT EXISTS idx_wartung_protokoll_tuer ON wartung_protokoll (tuer_id, status, datum);
CREATE INDEX IF NOT EXISTS idx_wartung_protokoll_faellig ON wartung_protokoll (naechste_wartung);
CREATE INDEX IF NOT EXISTS idx_wartung_protokoll_status ON wartung_protokoll (status);

-- Gewaehlte Module samt Bauart. Name und Schluessel werden mitgespeichert, damit ein spaeter
-- geloeschtes oder umbenanntes Modul das alte Protokoll nicht unlesbar macht.
CREATE TABLE IF NOT EXISTS wartung_protokoll_modul (
    protokoll_id BIGINT NOT NULL,
    modul_id BIGINT NOT NULL,
    modul_key VARCHAR(60) NOT NULL,
    modul_name VARCHAR(120) NOT NULL,
    untertyp_schluessel VARCHAR(30) NULL,
    untertyp_label VARCHAR(100) NULL,
    PRIMARY KEY (protokoll_id, modul_id),
    CONSTRAINT fk_wartung_protokoll_modul_protokoll FOREIGN KEY (protokoll_id) REFERENCES wartung_protokoll(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS wartung_protokoll_abschnitt (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    protokoll_id BIGINT NOT NULL,
    bereich VARCHAR(20) NOT NULL,
    label VARCHAR(200) NOT NULL,
    sortierung INT NOT NULL DEFAULT 0,
    CONSTRAINT fk_wartung_protokoll_abschnitt_protokoll FOREIGN KEY (protokoll_id) REFERENCES wartung_protokoll(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_wartung_protokoll_abschnitt_protokoll ON wartung_protokoll_abschnitt (protokoll_id);

-- vorlage_id verweist auf den Katalogeintrag, aus dem die Zeile kopiert wurde (ohne Fremdschluessel,
-- damit der Katalog frei umgebaut werden kann). vorheriges_ergebnis ist die Referenz aus dem letzten
-- abgeschlossenen Protokoll derselben Tuer.
CREATE TABLE IF NOT EXISTS wartung_protokoll_pruefpunkt (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    protokoll_id BIGINT NOT NULL,
    abschnitt_id BIGINT NULL,
    modul_key VARCHAR(60) NULL,
    vorlage_id BIGINT NULL,
    label VARCHAR(500) NOT NULL,
    ergebnis VARCHAR(20) NULL,
    bemerkung TEXT NULL,
    vorheriges_ergebnis VARCHAR(20) NULL,
    sortierung INT NOT NULL DEFAULT 0,
    CONSTRAINT fk_wartung_protokoll_pp_protokoll FOREIGN KEY (protokoll_id) REFERENCES wartung_protokoll(id) ON DELETE CASCADE,
    CONSTRAINT fk_wartung_protokoll_pp_abschnitt FOREIGN KEY (abschnitt_id) REFERENCES wartung_protokoll_abschnitt(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_wartung_protokoll_pp_protokoll ON wartung_protokoll_pruefpunkt (protokoll_id);

CREATE TABLE IF NOT EXISTS wartung_protokoll_datenfeld (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    protokoll_id BIGINT NOT NULL,
    abschnitt_id BIGINT NULL,
    modul_key VARCHAR(60) NULL,
    vorlage_id BIGINT NULL,
    label VARCHAR(200) NOT NULL,
    feldtyp VARCHAR(20) NOT NULL DEFAULT 'TEXT',
    optionen TEXT NULL,
    wert TEXT NULL,
    sortierung INT NOT NULL DEFAULT 0,
    CONSTRAINT fk_wartung_protokoll_df_protokoll FOREIGN KEY (protokoll_id) REFERENCES wartung_protokoll(id) ON DELETE CASCADE,
    CONSTRAINT fk_wartung_protokoll_df_abschnitt FOREIGN KEY (abschnitt_id) REFERENCES wartung_protokoll_abschnitt(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_wartung_protokoll_df_protokoll ON wartung_protokoll_datenfeld (protokoll_id);
