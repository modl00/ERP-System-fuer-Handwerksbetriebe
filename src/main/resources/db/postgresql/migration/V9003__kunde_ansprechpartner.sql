-- Portiert von db/migration/V903__kunde_ansprechpartner.sql (MySQL) nach PostgreSQL.
-- Kundenstamm: mehrere Ansprechpartner je Kunde. Idempotent.
--
-- kunde.ansprechspartner (ein Textfeld) bleibt bestehen: Es wird an vielen Stellen gelesen (E-Mails, Mahnungen,
-- Dokumente, Telefonsuche) und enthaelt kuenftig den Namen des Hauptansprechpartners aus dieser Tabelle.
-- Bestehende Eintraege werden als Hauptansprechpartner uebernommen (nur fuer Kunden ohne Zeile in der neuen Tabelle).

CREATE TABLE IF NOT EXISTS kunde_ansprechpartner (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    kunde_id BIGINT NOT NULL,
    name VARCHAR(200) NOT NULL,
    funktion VARCHAR(120) NULL,
    telefon VARCHAR(60) NULL,
    mobil VARCHAR(60) NULL,
    email VARCHAR(200) NULL,
    notizen TEXT NULL,
    haupt BOOLEAN NOT NULL DEFAULT FALSE,
    angelegt_am TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_kunde_ansprechpartner_kunde FOREIGN KEY (kunde_id) REFERENCES kunde(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_kunde_ansprechpartner_kunde ON kunde_ansprechpartner (kunde_id);

INSERT INTO kunde_ansprechpartner (kunde_id, name, haupt, angelegt_am)
SELECT k.id, LEFT(TRIM(k.ansprechspartner), 200), TRUE, NOW()
FROM kunde k
WHERE k.ansprechspartner IS NOT NULL
  AND TRIM(k.ansprechspartner) <> ''
  AND NOT EXISTS (SELECT 1 FROM kunde_ansprechpartner a WHERE a.kunde_id = k.id);
