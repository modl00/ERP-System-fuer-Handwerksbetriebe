-- Portiert von db/migration/V904__leistung_kalkulation.sql (MySQL) nach PostgreSQL.
-- Leistungen kalkulieren: Material (Artikel) und Arbeitszeit (Arbeitsgang) je Einheit der Leistung, dazu ein Zuschlag. Idempotent.
--
-- leistung.kalkuliert: Folgt der Preis der Kalkulation (TRUE) oder ist er von Hand eingetragen (FALSE, wie bisher)?
-- leistung.zuschlag_prozent: Zuschlag in Prozent auf Material und Arbeit (Gemeinkosten, Wagnis, Gewinn).
-- leistung.preis bleibt der gespeicherte Preis. Dokumente kopieren ihn beim Einfuegen: Aendert sich spaeter ein Artikelpreis, aendert sich
--   weder dieser Preis noch ein vorhandenes Dokument von selbst. Neu berechnet wird nur auf Wunsch.
-- leistung_position: eine Zeile je Artikel oder Arbeitsgang mit der Menge (Artikel) bzw. den Stunden (Arbeit) je 1 Einheit der Leistung.

ALTER TABLE leistung ADD COLUMN IF NOT EXISTS kalkuliert BOOLEAN NOT NULL DEFAULT FALSE;

ALTER TABLE leistung ADD COLUMN IF NOT EXISTS zuschlag_prozent DECIMAL(6,2) NULL;

CREATE TABLE IF NOT EXISTS leistung_position (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    leistung_id BIGINT NOT NULL,
    typ VARCHAR(20) NOT NULL,
    artikel_id BIGINT NULL,
    arbeitsgang_id BIGINT NULL,
    menge DECIMAL(12,3) NOT NULL,
    sort_order INT NOT NULL DEFAULT 0,
    notiz VARCHAR(255) NULL,
    CONSTRAINT fk_leistung_position_leistung FOREIGN KEY (leistung_id) REFERENCES leistung(id) ON DELETE CASCADE,
    CONSTRAINT fk_leistung_position_artikel FOREIGN KEY (artikel_id) REFERENCES artikel(id) ON DELETE CASCADE,
    CONSTRAINT fk_leistung_position_arbeitsgang FOREIGN KEY (arbeitsgang_id) REFERENCES arbeitsgang(id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_leistung_position_leistung ON leistung_position (leistung_id);
