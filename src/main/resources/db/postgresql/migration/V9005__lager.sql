-- Portiert von db/migration/V905__lager.sql (MySQL) nach PostgreSQL.
-- Lagerverwaltung (kleinster sinnvoller Umfang). Idempotent.
--
-- lagerort: wo Ware liegt (Halle, Fahrzeug, Regal ...). Wird nie geloescht, nur deaktiviert (Buchungen verweisen darauf).
-- lager_buchung: das Journal. Der Bestand ist immer die SUMME der Buchungen, es gibt keinen gespeicherten Zaehlerstand, der auseinanderlaufen koennte.
--   menge ist vorzeichenbehaftet: Zugang positiv, Abgang negativ, Korrektur (Inventur) die Differenz.
--   Die Menge steht in der Verrechnungseinheit des Artikels (Stueck, laufende Meter, Quadratmeter, Kilogramm).
--   artikel_in_projekt_id: Entnahme fuer eine Projektposition "aus Lager" (lose Verknuepfung ohne Fremdschluessel, die Position kann verschwinden).
-- lager_artikel: Einstellungen je Artikel (derzeit nur der Mindestbestand).

CREATE TABLE IF NOT EXISTS lagerort (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    beschreibung VARCHAR(255) NULL,
    aktiv BOOLEAN NOT NULL DEFAULT TRUE,
    sort_order INT NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_lagerort_name ON lagerort (name);

CREATE TABLE IF NOT EXISTS lager_buchung (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    artikel_id BIGINT NOT NULL,
    lagerort_id BIGINT NOT NULL,
    art VARCHAR(20) NOT NULL,
    menge DECIMAL(14,3) NOT NULL,
    gebucht_am TIMESTAMP(6) NOT NULL,
    projekt_id BIGINT NULL,
    artikel_in_projekt_id BIGINT NULL,
    notiz VARCHAR(255) NULL,
    benutzer VARCHAR(120) NULL,
    CONSTRAINT fk_lager_buchung_artikel FOREIGN KEY (artikel_id) REFERENCES artikel(id) ON DELETE CASCADE,
    CONSTRAINT fk_lager_buchung_lagerort FOREIGN KEY (lagerort_id) REFERENCES lagerort(id),
    CONSTRAINT fk_lager_buchung_projekt FOREIGN KEY (projekt_id) REFERENCES projekt(id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_lager_buchung_artikel ON lager_buchung (artikel_id, lagerort_id);
CREATE INDEX IF NOT EXISTS idx_lager_buchung_position ON lager_buchung (artikel_in_projekt_id);

CREATE TABLE IF NOT EXISTS lager_artikel (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    artikel_id BIGINT NOT NULL,
    mindestbestand DECIMAL(14,3) NULL,
    CONSTRAINT fk_lager_artikel_artikel FOREIGN KEY (artikel_id) REFERENCES artikel(id) ON DELETE CASCADE
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_lager_artikel_artikel ON lager_artikel (artikel_id);

-- Ein Lagerort zum Loslegen, nur wenn noch keiner existiert
INSERT INTO lagerort (name, beschreibung, aktiv, sort_order)
SELECT 'Hauptlager', 'Standard-Lagerort', TRUE, 0 
WHERE NOT EXISTS (SELECT 1 FROM lagerort);
