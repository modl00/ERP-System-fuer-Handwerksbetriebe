-- Portiert von db/migration/V910__wartung_vertrag.sql (MySQL) nach PostgreSQL.
-- Wartungsvertrag je Projekt: Laufzeit, Intervall und Preis der Wartung. Idempotent.
--
-- Ein Projekt hat hoechstens einen Vertrag (projekt_id ist eindeutig). Wird das Projekt geloescht, verschwindet sein Vertrag.
-- Aus dem Vertrag entstehen (noch) keine Feldeinsaetze und Rechnungen von selbst: Er haelt die Vereinbarung fest, die faelligen
-- Pruefungen kommen weiter aus dem Wartungsplan der Anlagen.

CREATE TABLE IF NOT EXISTS wartung_vertrag (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NULL,
    projekt_id BIGINT NOT NULL,
    vertragsnummer VARCHAR(60) NULL,
    beginn DATE NOT NULL,
    ende DATE NULL,
    intervall_monate INT NOT NULL DEFAULT 12,
    preis_netto DECIMAL(12,2) NULL,
    notiz VARCHAR(1000) NULL,
    angelegt_am TIMESTAMP(6) NOT NULL,
    geaendert_am TIMESTAMP(6) NOT NULL,
    CONSTRAINT uq_wartung_vertrag_projekt UNIQUE (projekt_id),
    CONSTRAINT fk_wartung_vertrag_projekt FOREIGN KEY (projekt_id) REFERENCES projekt(id) ON DELETE CASCADE
);
