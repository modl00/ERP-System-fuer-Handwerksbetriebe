-- Portiert von db/migration/V912__abteilung_funktionsrecht.sql (MySQL) nach PostgreSQL.
-- Rechte je Abteilung für Funktionen des Programms (Web und Handy-App). Idempotent.
--
-- Je Abteilung und Funktion eine Zeile mit den vier Rechten Ansehen, Anlegen, Ändern und Löschen. Ohne Zeile gilt "erlaubt", damit sich nach dem
-- Update nichts ändert; eingeschränkt wird erst, wenn in der Rechteverwaltung gespeichert wird. Die Funktion steht als Text, damit neue
-- Funktionen ohne Migration dazukommen können.

CREATE TABLE IF NOT EXISTS abteilung_funktionsrecht (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    abteilung_id BIGINT NOT NULL,
    funktion VARCHAR(40) NOT NULL,
    ansehen BOOLEAN NOT NULL DEFAULT TRUE,
    anlegen BOOLEAN NOT NULL DEFAULT TRUE,
    aendern BOOLEAN NOT NULL DEFAULT TRUE,
    loeschen BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_abteilung_funktionsrecht UNIQUE (abteilung_id, funktion),
    CONSTRAINT fk_abteilung_funktionsrecht_abteilung FOREIGN KEY (abteilung_id) REFERENCES abteilung(id) ON DELETE CASCADE
);
