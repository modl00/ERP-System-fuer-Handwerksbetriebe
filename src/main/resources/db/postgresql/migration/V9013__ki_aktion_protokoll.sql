-- Portiert von db/migration/V913__ki_aktion_protokoll.sql (MySQL) nach PostgreSQL.
-- Protokoll der KI-Aktionen (Auskünfte und bestätigte Änderungen des KI-Assistenten). Idempotent.
--
-- Jede Nutzung eines Werkzeugs durch die KI steht hier: wer, wann, mit welchem Anbieter und Modell, welches Werkzeug, mit welchen Angaben und was
-- daraus wurde (ausgeführt, vorgeschlagen, bestätigt, verworfen, Fehler). Das Protokoll wird nur gelesen und hinzugefügt, nie geändert.

CREATE TABLE IF NOT EXISTS ki_aktion_protokoll (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zeit TIMESTAMP(6) NOT NULL,
    profil_id BIGINT NULL,
    benutzer VARCHAR(120) NULL,
    funktion VARCHAR(40) NOT NULL,
    anbieter VARCHAR(20) NOT NULL,
    modell VARCHAR(120) NULL,
    werkzeug VARCHAR(80) NOT NULL,
    parameter TEXT NULL,
    status VARCHAR(20) NOT NULL,
    ergebnis VARCHAR(2000) NULL
);
CREATE INDEX IF NOT EXISTS ix_ki_aktion_protokoll_zeit ON ki_aktion_protokoll (zeit);
