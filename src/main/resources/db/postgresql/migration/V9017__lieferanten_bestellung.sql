-- Portiert von db/migration/V917__lieferanten_bestellung.sql (MySQL) nach PostgreSQL.
-- Bestellwesen Stufe 1 (#86): Bestellung an einen Lieferanten als eigener Datensatz mit Bestellnummer, Positionen und Stand. Idempotent.
--
-- Eine Bestellung gehört einem Lieferanten und darf Positionen aus mehreren Projekten, aus dem Lager (Mindestbestand) und frei aus dem Artikelstamm
-- enthalten. Entwürfe haben noch keine Bestellnummer; sie wird beim Bestellen lückenlos je Monat vergeben (Zähler in dokumentnummer_counter).
-- Bisherige "bestellt"-Markierungen an Projektpositionen bleiben unverändert (Altbestand ohne Bestellnummer).

CREATE TABLE IF NOT EXISTS lieferanten_bestellung (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NULL,
    bestellnummer VARCHAR(30) NULL,
    lieferant_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL,
    notiz VARCHAR(1000) NULL,
    erstellt_am TIMESTAMP(6) NOT NULL,
    erstellt_von VARCHAR(120) NULL,
    bestellt_am TIMESTAMP(6) NULL,
    bestellt_von VARCHAR(120) NULL,
    bestellt_per VARCHAR(20) NULL,
    storniert_am TIMESTAMP(6) NULL,
    storno_grund VARCHAR(500) NULL,
    CONSTRAINT fk_lieferanten_bestellung_lieferant FOREIGN KEY (lieferant_id) REFERENCES lieferanten (id)
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_lieferanten_bestellung_nummer ON lieferanten_bestellung (bestellnummer);
CREATE INDEX IF NOT EXISTS ix_lieferanten_bestellung_status ON lieferanten_bestellung (status);
CREATE INDEX IF NOT EXISTS ix_lieferanten_bestellung_lieferant ON lieferanten_bestellung (lieferant_id);

CREATE TABLE IF NOT EXISTS bestell_position (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bestellung_id BIGINT NOT NULL,
    artikel_id BIGINT NULL,
    artikelnummer VARCHAR(64) NULL,
    bezeichnung VARCHAR(500) NOT NULL,
    menge DECIMAL(14,3) NOT NULL,
    einheit VARCHAR(20) NOT NULL,
    einzelpreis DECIMAL(19,4) NULL,
    herkunft VARCHAR(10) NOT NULL,
    projekt_id BIGINT NULL,
    artikel_in_projekt_id BIGINT NULL,
    kommentar VARCHAR(500) NULL,
    geliefert_am DATE NULL,
    CONSTRAINT fk_bestell_position_bestellung FOREIGN KEY (bestellung_id) REFERENCES lieferanten_bestellung (id) ON DELETE CASCADE,
    CONSTRAINT fk_bestell_position_artikel FOREIGN KEY (artikel_id) REFERENCES artikel (id),
    CONSTRAINT fk_bestell_position_projekt FOREIGN KEY (projekt_id) REFERENCES projekt (id)
);
CREATE INDEX IF NOT EXISTS ix_bestell_position_bestellung ON bestell_position (bestellung_id);
CREATE INDEX IF NOT EXISTS ix_bestell_position_artikel ON bestell_position (artikel_id);
CREATE INDEX IF NOT EXISTS ix_bestell_position_projekt ON bestell_position (projekt_id);
