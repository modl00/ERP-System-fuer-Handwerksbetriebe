-- Portiert von db/migration/V918__material_rechnung_zuordnung.sql (MySQL) nach PostgreSQL.
-- Material "kommt per Rechnung" aufloesen (#99, Stufe 1): welche Rechnung hat welches Projektmaterial bezahlt. Idempotent.
--
-- Eine Zeile sagt: Von der Eingangsrechnung (dokument_id) gehoert der Betrag zur geplanten Materialposition des Projekts (artikel_in_projekt_id).
-- Ohne Materialposition ist es "Material ohne Plan" (spontaner Kauf, mit Beschreibung). Die Zeilen haengen am Dokument und am Projekt, nicht am Projektanteil:
-- Der Anteil wird beim Bearbeiten der Zuordnung neu angelegt, die Verknuepfung muss das ueberleben.
-- Die Projektkosten aendern sich dadurch nicht (sie kommen weiter aus den Rechnungsanteilen; geplantes Material zaehlt nicht mit).

CREATE TABLE IF NOT EXISTS material_rechnung_zuordnung (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dokument_id BIGINT NOT NULL,
    projekt_id BIGINT NOT NULL,
    artikel_in_projekt_id BIGINT NULL,
    betrag DECIMAL(12,2) NOT NULL,
    beschreibung VARCHAR(255) NULL,
    zugeordnet_am TIMESTAMP(6) NOT NULL,
    zugeordnet_von VARCHAR(120) NULL,
    CONSTRAINT fk_material_rechnung_dokument FOREIGN KEY (dokument_id) REFERENCES lieferant_dokument (id) ON DELETE CASCADE,
    CONSTRAINT fk_material_rechnung_projekt FOREIGN KEY (projekt_id) REFERENCES projekt (id) ON DELETE CASCADE,
    CONSTRAINT fk_material_rechnung_position FOREIGN KEY (artikel_in_projekt_id) REFERENCES artikel_in_projekt (id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS ix_material_rechnung_dokument_projekt ON material_rechnung_zuordnung (dokument_id, projekt_id);
CREATE INDEX IF NOT EXISTS ix_material_rechnung_position ON material_rechnung_zuordnung (artikel_in_projekt_id);
