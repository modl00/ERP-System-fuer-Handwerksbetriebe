-- Portiert von db/migration/V919__aktivitaet_ereignis.sql (MySQL) nach PostgreSQL.
-- Aktivitaetsprotokoll "Mein Tagesverlauf" (#93, Stufe 1): ein gemeinsames Ereignisprotokoll. Idempotent.
--
-- Gespeichert wird nur WER, WANN, WAS (Art) und WORAN (Objektart, Nummer, Name): keine Inhalte (keine Mailtexte, keine Betraege).
-- Die GoBD-Pruefprotokolle der Rechnungen und Belege bleiben davon unberuehrt; dieses Protokoll ergaenzt sie, es ersetzt nichts.
-- Aufbewahrung und Schalter fuer Mitarbeiter stehen in den Einstellungen (aktivitaet.aufbewahrung-tage, aktivitaet.mitarbeiter-aktiv).

CREATE TABLE IF NOT EXISTS aktivitaet_ereignis (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profil_id BIGINT NULL,
    benutzer VARCHAR(120) NULL,
    zeitpunkt TIMESTAMP(6) NOT NULL,
    art VARCHAR(20) NOT NULL,
    objekt_typ VARCHAR(30) NULL,
    objekt_id BIGINT NULL,
    objekt_name VARCHAR(200) NULL,
    beschreibung VARCHAR(160) NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_aktivitaet_profil_zeit ON aktivitaet_ereignis (profil_id, zeitpunkt);
CREATE INDEX IF NOT EXISTS ix_aktivitaet_objekt ON aktivitaet_ereignis (objekt_typ, objekt_id);
CREATE INDEX IF NOT EXISTS ix_aktivitaet_zeit ON aktivitaet_ereignis (zeitpunkt);
