CREATE TABLE IF NOT EXISTS wartung_import_zuordnung (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quelle VARCHAR(30) NOT NULL,
    typ VARCHAR(20) NOT NULL,
    alt_id BIGINT NOT NULL,
    erp_id BIGINT NOT NULL,
    importiert_am TIMESTAMP(6) NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_wartung_import_zuordnung ON wartung_import_zuordnung (quelle, typ, alt_id);
