-- Portiert von db/migration/V928__nummernkreis.sql (MySQL) nach PostgreSQL.
-- Einstellbare Nummernkreise (Issue #62). Idempotent.
--
-- nummernkreis: je Dokumentart ein eigenes Format (Praefix, Datumsteil, Ruecksetzung, Stellen, Startnummer). Ohne Zeile gilt das bisherige Format
--   (PRAEFIX-JJJJ/MM/NNNNN mit einem gemeinsamen Monatszaehler), damit sich nach dem Update nichts aendert.
-- nummernkreis_zaehler: der letzte vergebene Wert je Dokumentart und Zeitraum ("alle", "2026" oder "2026-10"); wird unter Sperre erhoeht.

CREATE TABLE IF NOT EXISTS nummernkreis (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    art VARCHAR(40) NOT NULL,
    praefix VARCHAR(10) NOT NULL,
    datumsteil VARCHAR(20) NOT NULL,
    ruecksetzung VARCHAR(20) NOT NULL,
    stellen INT NOT NULL,
    startnummer BIGINT NOT NULL,
    CONSTRAINT uq_nummernkreis_art UNIQUE (art)
);

CREATE TABLE IF NOT EXISTS nummernkreis_zaehler (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    art VARCHAR(40) NOT NULL,
    periode VARCHAR(20) NOT NULL,
    letzte BIGINT NOT NULL,
    CONSTRAINT uq_nummernkreis_zaehler UNIQUE (art, periode)
);
