-- Portiert von db/migration/V929__lieferschein.sql (MySQL) nach PostgreSQL.
-- Lieferschein an Kunden mit Unterschrift des Empfaengers (Issue #128, Stufe Lieferschein) und
-- Nummernbereiche je Mitarbeiter fuer das Arbeiten ohne Netz. Idempotent.
--
-- lieferschein.client_id: vom Geraet vergebene Kennung, damit ein wiederholtes Senden (Verbindungsabbruch, Abgleich) keinen zweiten Lieferschein anlegt.
-- nummernreservierung: vorab reservierte Nummern; "RESERVIERT" = noch nicht verwendet (bleibt als Luecke dokumentiert), "VERWENDET" = einem Lieferschein zugeordnet.

CREATE TABLE IF NOT EXISTS lieferschein (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nummer VARCHAR(60) NOT NULL,
    client_id VARCHAR(64) NULL,
    kunde_id BIGINT NULL,
    projekt_id BIGINT NULL,
    empfaenger_name VARCHAR(200) NOT NULL,
    datum DATE NOT NULL,
    bemerkung TEXT NULL,
    unterschrift_bild TEXT NULL,
    unterschrift_name VARCHAR(200) NULL,
    unterschrieben_am TIMESTAMP(6) NULL,
    erstellt_von_id BIGINT NULL,
    erstellt_am TIMESTAMP(6) NOT NULL,
    kopie_an VARCHAR(255) NULL,
    kopie_gesendet_am TIMESTAMP(6) NULL,
    CONSTRAINT uq_lieferschein_nummer UNIQUE (nummer),
    CONSTRAINT uq_lieferschein_client UNIQUE (client_id),
    CONSTRAINT fk_lieferschein_kunde FOREIGN KEY (kunde_id) REFERENCES kunde (id),
    CONSTRAINT fk_lieferschein_projekt FOREIGN KEY (projekt_id) REFERENCES projekt (id),
    CONSTRAINT fk_lieferschein_mitarbeiter FOREIGN KEY (erstellt_von_id) REFERENCES mitarbeiter (id)
);

CREATE TABLE IF NOT EXISTS lieferschein_position (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lieferschein_id BIGINT NOT NULL,
    sortierung INT NOT NULL,
    bezeichnung VARCHAR(300) NOT NULL,
    menge DECIMAL(14,3) NOT NULL,
    einheit VARCHAR(20) NULL,
    CONSTRAINT fk_lieferschein_position FOREIGN KEY (lieferschein_id) REFERENCES lieferschein (id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS nummernreservierung (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    art VARCHAR(40) NOT NULL,
    nummer VARCHAR(60) NOT NULL,
    mitarbeiter_id BIGINT NOT NULL,
    reserviert_am TIMESTAMP(6) NOT NULL,
    status VARCHAR(20) NOT NULL,
    verwendet_am TIMESTAMP(6) NULL,
    CONSTRAINT uq_nummernreservierung UNIQUE (art, nummer),
    CONSTRAINT fk_nummernreservierung_mitarbeiter FOREIGN KEY (mitarbeiter_id) REFERENCES mitarbeiter (id)
);
