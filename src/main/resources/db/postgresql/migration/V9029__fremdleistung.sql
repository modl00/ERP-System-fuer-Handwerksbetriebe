-- Portiert von db/migration/V930__fremdleistung.sql (MySQL) nach PostgreSQL.
-- Fremdleistung in der Leistungskalkulation (Stufe 4 von #135): Preisliste je Veredler (Lieferant), zum Beispiel Verzinken, Pulverbeschichten, Fraesen. Idempotent.
--
-- fremdleistung: ein Angebot eines Veredlers mit allen Kostenarten; jede ist einzeln aus- oder abschaltbar (leer = gibt es nicht):
--   preis_je_einheit (je kg, m2, m oder Stueck), mindestpreis (je Auftrag), einmal_betrag (je Auftrag), anteil_betrag (je Charge, verteilt auf die Menge),
--   prozent_zuschlag (auf die Summe der uebrigen Kosten), Transport (Pauschal, je kg, je Fahrt, je km hin und zurueck), sonstige Kosten (Text mit Betrag).
-- leistung_position.fremdleistung_id: die gewaehlte Fremdleistung einer Zeile; gewicht_kg_je_einheit: Gewicht je Einheit der Leistung (nur noetig fuer Transport je kg,
--   wenn die Fremdleistung nicht nach kg abgerechnet wird).

CREATE TABLE IF NOT EXISTS fremdleistung (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lieferant_id BIGINT NOT NULL,
    bezeichnung VARCHAR(200) NOT NULL,
    einheit VARCHAR(20) NOT NULL,
    preis_je_einheit DECIMAL(12,4) NULL,
    mindestpreis DECIMAL(12,2) NULL,
    einmal_betrag DECIMAL(12,2) NULL,
    anteil_betrag DECIMAL(12,2) NULL,
    anteil_chargenmenge DECIMAL(12,3) NULL,
    prozent_zuschlag DECIMAL(6,2) NULL,
    transport_art VARCHAR(20) NOT NULL DEFAULT 'KEINE',
    transport_betrag DECIMAL(12,4) NULL,
    transport_km DECIMAL(8,2) NULL,
    transport_fahrten INT NOT NULL DEFAULT 1,
    sonstige_bezeichnung VARCHAR(100) NULL,
    sonstige_betrag DECIMAL(12,2) NULL,
    gueltig_ab DATE NOT NULL,
    aktiv BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_fremdleistung_lieferant FOREIGN KEY (lieferant_id) REFERENCES lieferanten (id)
);

ALTER TABLE leistung_position ADD COLUMN IF NOT EXISTS fremdleistung_id BIGINT NULL;

ALTER TABLE leistung_position ADD COLUMN IF NOT EXISTS gewicht_kg_je_einheit DECIMAL(12,3) NULL;

ALTER TABLE leistung_position DROP CONSTRAINT IF EXISTS fk_leistung_position_fremdleistung;
ALTER TABLE leistung_position ADD CONSTRAINT fk_leistung_position_fremdleistung FOREIGN KEY (fremdleistung_id) REFERENCES fremdleistung (id);
