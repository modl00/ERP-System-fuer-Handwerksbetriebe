-- Portiert von db/migration/V933__maschinenliste.sql (MySQL) nach PostgreSQL.
-- Kostenrechnung Stufe 2 (#166): Maschinenliste mit Rechner. Idempotent.
--
-- maschine: Name, Anschaffung, Restwert, Nutzungsdauer, Zins, Wartung/Platz/Versicherung je Jahr, kW, Strompreis, Auslastung, Laufstunden je Jahr,
--   satz_von_hand (leer = errechnet) und kostensatz (der Satz je Laufstunde, mit dem gerechnet wird).
-- maschine_satz_verlauf: jede Aenderung des Satzes mit Datum und Bearbeiter.
-- arbeitsgang.maschine_id: die Maschine aus der Liste; gesetzt gilt deren Satz. Der alte Satz am Arbeitsgang wird beim Start durch die Anwendung
--   in eine Maschine uebernommen (MaschinenUebernahmeRunner), damit die Preise gleich bleiben; er laeuft auch ohne Flyway (Windows/H2).

CREATE TABLE IF NOT EXISTS maschine (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NULL,
    name VARCHAR(100) NOT NULL,
    anschaffungswert DECIMAL(12,2) NULL,
    restwert DECIMAL(12,2) NULL,
    nutzungsdauer_jahre DECIMAL(5,2) NULL,
    zinssatz_prozent DECIMAL(5,2) NULL,
    wartung_je_jahr DECIMAL(12,2) NULL,
    platz_je_jahr DECIMAL(12,2) NULL,
    versicherung_je_jahr DECIMAL(12,2) NULL,
    leistung_kw DECIMAL(8,2) NULL,
    strompreis_je_kwh DECIMAL(8,4) NULL,
    auslastung_prozent DECIMAL(5,2) NULL,
    laufstunden_je_jahr DECIMAL(8,1) NULL,
    satz_von_hand DECIMAL(10,2) NULL,
    kostensatz DECIMAL(10,2) NOT NULL,
    aktiv BOOLEAN NOT NULL DEFAULT TRUE,
    bemerkung VARCHAR(500) NULL,
    angelegt_am TIMESTAMP(6) NOT NULL
);

CREATE TABLE IF NOT EXISTS maschine_satz_verlauf (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    maschine_id BIGINT NOT NULL,
    satz DECIMAL(10,2) NOT NULL,
    von_hand BOOLEAN NOT NULL,
    gueltig_ab DATE NOT NULL,
    geaendert_von VARCHAR(120) NULL,
    geaendert_am TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_maschine_satz_verlauf_maschine FOREIGN KEY (maschine_id) REFERENCES maschine (id) ON DELETE CASCADE
);

ALTER TABLE arbeitsgang ADD COLUMN IF NOT EXISTS maschine_id BIGINT NULL;

ALTER TABLE arbeitsgang DROP CONSTRAINT IF EXISTS fk_arbeitsgang_maschine;
ALTER TABLE arbeitsgang ADD CONSTRAINT fk_arbeitsgang_maschine FOREIGN KEY (maschine_id) REFERENCES maschine (id);
