-- KI-Merkliste (#123): Was die KI sich merken soll ("Dazulernen"). Nur durch Bestätigung eines Administrators entstanden, in den Einstellungen sichtbar und löschbar. Idempotent.
CREATE TABLE IF NOT EXISTS ki_merkzettel (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    satz VARCHAR(500) NOT NULL,
    angelegt_von VARCHAR(120) NULL,
    angelegt_am TIMESTAMP(6) NOT NULL
);
