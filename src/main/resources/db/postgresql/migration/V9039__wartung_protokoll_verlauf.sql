-- Wartungsbericht nachträglich ändern (#238): Wer hat ein Protokoll wann abgeschlossen, wieder geöffnet oder archiviert (mit Grund). Idempotent.
CREATE TABLE IF NOT EXISTS wartung_protokoll_verlauf (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    protokoll_id BIGINT NOT NULL,
    zeit TIMESTAMP(6) NOT NULL,
    benutzer VARCHAR(120) NULL,
    von_status VARCHAR(20) NOT NULL,
    nach_status VARCHAR(20) NOT NULL,
    grund VARCHAR(500) NULL,
    PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS idx_wartung_protokoll_verlauf_protokoll ON wartung_protokoll_verlauf (protokoll_id, zeit);
