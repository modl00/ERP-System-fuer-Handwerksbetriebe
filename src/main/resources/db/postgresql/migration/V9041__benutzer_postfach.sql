-- Portiert von db/migration/V942__benutzer_postfach.sql (MySQL) nach PostgreSQL.
-- Persönliche Postfächer je Benutzer (Stufe 1 von Issue #272): Zugangsdaten (Passwort verschlüsselt), Server und spätere Ordnerauswahl. Idempotent.
CREATE TABLE IF NOT EXISTS benutzer_postfach (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    profil_id BIGINT NOT NULL,
    bezeichnung VARCHAR(120) NOT NULL,
    email_adresse VARCHAR(255) NOT NULL,
    imap_host VARCHAR(255) NOT NULL,
    imap_port INT NOT NULL,
    smtp_host VARCHAR(255) NULL,
    smtp_port INT NULL,
    benutzername VARCHAR(255) NOT NULL,
    passwort_verschluesselt VARCHAR(1000) NOT NULL,
    aktiv BOOLEAN NOT NULL DEFAULT TRUE,
    ordner_auswahl VARCHAR(4000) NULL,
    erstellt_am TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_benutzer_postfach_profil FOREIGN KEY (profil_id) REFERENCES frontend_user_profile (id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_benutzer_postfach_profil ON benutzer_postfach (profil_id);
