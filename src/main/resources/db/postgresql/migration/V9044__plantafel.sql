-- Portiert von db/migration/V945__plantafel.sql (MySQL) nach PostgreSQL.
-- Plantafel (#184), Stufe 1: Vorgangsarten, Vorgänge je Auftrag (Projekt), Abhängigkeiten und Termine je Auftrag.
-- Keine Enum-Spalten (Status als Text). Idempotent (IF NOT EXISTS, Vorgangsarten nur wenn die Tabelle leer ist).

CREATE TABLE IF NOT EXISTS plan_vorgangstyp (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    farbe VARCHAR(9) NOT NULL DEFAULT '#be123c',
    sortierung INT NOT NULL DEFAULT 0,
    standard_dauer_tage INT NOT NULL DEFAULT 1,
    aktiv BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_plan_vorgangstyp_name UNIQUE (name)
);

CREATE TABLE IF NOT EXISTS plan_projekt (
    projekt_id BIGINT NOT NULL PRIMARY KEY,
    start_datum DATE NULL,
    ziel_datum DATE NULL,
    CONSTRAINT fk_plan_projekt_projekt FOREIGN KEY (projekt_id) REFERENCES projekt (id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS plan_vorgang (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    projekt_id BIGINT NOT NULL,
    typ_id BIGINT NOT NULL,
    bezeichnung VARCHAR(200) NOT NULL,
    dauer_tage INT NOT NULL DEFAULT 1,
    dauer_herkunft VARCHAR(20) NOT NULL DEFAULT 'GESCHAETZT',
    fester_start DATE NULL,
    start_datum DATE NULL,
    ende_datum DATE NULL,
    konflikt BOOLEAN NOT NULL DEFAULT FALSE,
    status VARCHAR(20) NOT NULL DEFAULT 'GEPLANT',
    sortierung INT NOT NULL DEFAULT 0,
    notiz VARCHAR(1000) NULL,
    CONSTRAINT fk_plan_vorgang_projekt FOREIGN KEY (projekt_id) REFERENCES projekt (id) ON DELETE CASCADE,
    CONSTRAINT fk_plan_vorgang_typ FOREIGN KEY (typ_id) REFERENCES plan_vorgangstyp (id)
);

CREATE TABLE IF NOT EXISTS plan_abhaengigkeit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vorgang_id BIGINT NOT NULL,
    vorgaenger_id BIGINT NOT NULL,
    versatz_tage INT NOT NULL DEFAULT 0,
    CONSTRAINT uq_plan_abhaengigkeit UNIQUE (vorgang_id, vorgaenger_id),
    CONSTRAINT fk_plan_abh_vorgang FOREIGN KEY (vorgang_id) REFERENCES plan_vorgang (id) ON DELETE CASCADE,
    CONSTRAINT fk_plan_abh_vorgaenger FOREIGN KEY (vorgaenger_id) REFERENCES plan_vorgang (id) ON DELETE CASCADE
);

INSERT INTO plan_vorgangstyp (name, farbe, sortierung, standard_dauer_tage)
SELECT v.name, v.farbe, v.sortierung, v.tage FROM (
    SELECT 'Planung' AS name, '#6366f1' AS farbe, 10 AS sortierung, 2 AS tage
    UNION ALL SELECT 'Materialbeschaffung', '#d97706', 20, 5
    UNION ALL SELECT 'Fertigung', '#be123c', 30, 5
    UNION ALL SELECT 'Veredelung', '#0891b2', 40, 5
    UNION ALL SELECT 'Montage', '#059669', 50, 2
) v
WHERE NOT EXISTS (SELECT 1 FROM plan_vorgangstyp);
