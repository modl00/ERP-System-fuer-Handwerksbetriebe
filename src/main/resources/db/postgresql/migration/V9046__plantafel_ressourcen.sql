-- Plantafel (#323), Stufe 1: Ressourcen (Werkstatt, Fahrzeug, Maschine …) und die Zuweisung von Mitarbeitern und Ressource zu einem Vorgang.
-- Keine Enum-Spalten (Art und Priorität als Text). Idempotent. Bestehende Vorgänge bleiben unverändert (keine Zuweisung, Priorität NORMAL).

CREATE TABLE IF NOT EXISTS plan_ressource (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    art VARCHAR(20) NOT NULL DEFAULT 'SONSTIGE',
    sortierung INT NOT NULL DEFAULT 0,
    aktiv BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_plan_ressource_name UNIQUE (name)
);

INSERT INTO plan_ressource (name, art, sortierung)
SELECT r.name, r.art, r.sortierung FROM (
    SELECT 'Büro' AS name, 'ORT' AS art, 10 AS sortierung
    UNION ALL SELECT 'Werkstatt', 'ORT', 20
    UNION ALL SELECT 'Vor Ort', 'ORT', 30
    UNION ALL SELECT 'Fremdfertigung', 'EXTERN', 40
) r
WHERE NOT EXISTS (SELECT 1 FROM plan_ressource);

ALTER TABLE plan_vorgang ADD COLUMN IF NOT EXISTS ressource_id BIGINT NULL;
ALTER TABLE plan_vorgang ADD COLUMN IF NOT EXISTS prioritaet VARCHAR(20) NOT NULL DEFAULT 'NORMAL';

CREATE TABLE IF NOT EXISTS plan_vorgang_mitarbeiter (
    vorgang_id BIGINT NOT NULL,
    mitarbeiter_id BIGINT NOT NULL,
    PRIMARY KEY (vorgang_id, mitarbeiter_id),
    CONSTRAINT fk_plan_vm_vorgang FOREIGN KEY (vorgang_id) REFERENCES plan_vorgang (id) ON DELETE CASCADE,
    CONSTRAINT fk_plan_vm_mitarbeiter FOREIGN KEY (mitarbeiter_id) REFERENCES mitarbeiter (id) ON DELETE CASCADE
);
