-- Portiert von db/migration/V950__plantafel_stundenrechnung.sql (MySQL) nach PostgreSQL.
-- Plantafel (#331), Stufe 2: Stundenrechnung. Ein Arbeitsvorgang hat einen Aufwand in Stunden und braucht Personen, ein Wartevorgang (Material, Fremdleistung) nur Zeit.
-- Dazu: "frühestens ab" (getrennt vom festen Start), Reihenfolge je Person (Entscheidung des Planers), Hinweis zur Verspätung, die gerechnete Zuteilung je Person und Tag
-- und der Wochenrhythmus ("Bürotag") je Vorgangsart. Idempotent, keine Enum-Spalten. Bestehende Vorgänge bleiben unverändert:
-- Ohne Aufwand rechnet das Programm Dauer in Tagen mal Standard-Arbeitstag.

ALTER TABLE plan_vorgang ADD COLUMN IF NOT EXISTS aufwand_stunden DECIMAL(9,2) NULL;

ALTER TABLE plan_vorgang ADD COLUMN IF NOT EXISTS aufwand_herkunft VARCHAR(20) NOT NULL DEFAULT 'GESCHAETZT';

ALTER TABLE plan_vorgang ADD COLUMN IF NOT EXISTS fruehestens_ab DATE NULL;

ALTER TABLE plan_vorgang ADD COLUMN IF NOT EXISTS rang INT NULL;

ALTER TABLE plan_vorgang ADD COLUMN IF NOT EXISTS hinweis VARCHAR(1000) NULL;

ALTER TABLE plan_vorgang ADD COLUMN IF NOT EXISTS ohne_zuweisung_geschaetzt BOOLEAN NOT NULL DEFAULT FALSE;

-- Wartevorgang: braucht keine Personen, nur Zeit. Vorgabe für Material und Veredelung (nur beim ersten Anlegen der Spalte).
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = current_schema() AND table_name = 'plan_vorgangstyp' AND column_name = 'wartet') THEN
        ALTER TABLE plan_vorgangstyp ADD COLUMN wartet BOOLEAN NOT NULL DEFAULT FALSE;
        UPDATE plan_vorgangstyp SET wartet = TRUE WHERE name IN ('Materialbeschaffung', 'Veredelung');
    END IF;
END $$;

-- Bürotag: Vorgänge dieser Art zählen auch an Bürotagen einer Person (alle anderen nicht).
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = current_schema() AND table_name = 'plan_vorgangstyp' AND column_name = 'buero') THEN
        ALTER TABLE plan_vorgangstyp ADD COLUMN buero BOOLEAN NOT NULL DEFAULT FALSE;
        UPDATE plan_vorgangstyp SET buero = TRUE WHERE name = 'Planung';
    END IF;
END $$;

-- Die gerechnete Zuteilung: wer arbeitet an welchem Tag wie viele Stunden an welchem Vorgang (mitarbeiter_id leer = Standardwert, noch niemand zugewiesen).
CREATE TABLE IF NOT EXISTS plan_zuteilung (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vorgang_id BIGINT NOT NULL,
    mitarbeiter_id BIGINT NULL,
    datum DATE NOT NULL,
    stunden DECIMAL(7,2) NOT NULL,
    CONSTRAINT fk_plan_zuteilung_vorgang FOREIGN KEY (vorgang_id) REFERENCES plan_vorgang (id) ON DELETE CASCADE
);
CREATE INDEX IF NOT EXISTS idx_plan_zuteilung_datum ON plan_zuteilung (datum);
CREATE INDEX IF NOT EXISTS idx_plan_zuteilung_vorgang ON plan_zuteilung (vorgang_id);
