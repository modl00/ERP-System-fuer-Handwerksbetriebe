-- Portiert von db/migration/V951__plantafel_aenderungen.sql (MySQL) nach PostgreSQL.
-- Plantafel (#331, Stufe 4): Änderungsliste mit Rückgängig und Schutz vor gleichzeitigem Bearbeiten. Idempotent, keine Enum-Spalten.
-- plan_vorgang.bearbeitung zählt nur Änderungen von Hand (nicht die automatische Neuberechnung): Wer einen Vorgang speichert, den inzwischen jemand anderes geändert hat, bekommt eine Meldung.
-- plan_aenderung: die letzten Änderungen mit dem Zustand davor (JSON); leer = lässt sich nicht zurücknehmen (zum Beispiel Anlegen oder Löschen).

ALTER TABLE plan_vorgang ADD COLUMN IF NOT EXISTS bearbeitung INT NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS plan_aenderung (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zeitpunkt TIMESTAMP(6) NOT NULL,
    benutzer VARCHAR(100) NULL,
    vorgang_id BIGINT NULL,
    projekt_id BIGINT NULL,
    beschreibung VARCHAR(500) NOT NULL,
    vorher TEXT NULL,
    rueckgaengig_am TIMESTAMP(6) NULL
);
CREATE INDEX IF NOT EXISTS idx_plan_aenderung_zeitpunkt ON plan_aenderung (zeitpunkt);
